import AppKit

@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()
    private var lastChange = NSPasteboard.general.changeCount
    private var ownChanges = Set<Int>()
    private var timer: Timer?

    /// Called for every captured item (used by Paste Stack).
    var onCapture: ((ClipItem) -> Void)?

    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    static let maxRepBytes = 25 * 1024 * 1024

    func start() {
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardMonitor.shared.poll() }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    /// Mark a pasteboard change as ours so it isn't captured as new history.
    func markOwnChange() {
        let c = NSPasteboard.general.changeCount
        ownChanges.insert(c)
        lastChange = c
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ownChanges.remove(pb.changeCount) != nil { return }
        let s = Settings.shared
        if s.isPaused { return }
        let types = pb.types ?? []
        if s.ignoreConfidential && types.contains(Self.concealed) { return }
        if s.ignoreTransient && (types.contains(Self.transient) || types.contains(Self.autoGenerated)) { return }

        let front = NSWorkspace.shared.frontmostApplication
        var bundleID = front?.bundleIdentifier
        var appName = front?.localizedName
        if let src = pb.string(forType: Self.source), !src.isEmpty, src != bundleID,
           let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: src) {
            bundleID = src
            appName = FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
        }
        if let b = bundleID, s.ignoredApps.contains(where: { $0.bundleID == b }) { return }

        guard let captured = Self.capture(pb, bundleID: bundleID, appName: appName) else { return }
        let (item, isNew) = ClipStore.shared.insert(captured.item, blobs: captured.blobs, thumbnail: captured.thumbnail)
        if isNew { Enrichment.process(item) }
        if s.soundsEnabled { NSSound(named: "Tink")?.play() }
        onCapture?(item)
    }

    struct Captured {
        var item: ClipItem
        var blobs: [String: Data]
        var thumbnail: Data?
    }

    static func capture(_ pb: NSPasteboard, bundleID: String?, appName: String?) -> Captured? {
        guard let first = pb.pasteboardItems?.first else { return nil }
        let types = pb.types ?? []
        var item = ClipItem(kind: .text, hash: "")
        item.sourceBundleID = bundleID
        item.sourceAppName = appName
        item.device = Host.current().localizedName
        var blobs: [String: Data] = [:]
        var thumbnail: Data?

        let fileURLs = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if types.contains(.fileURL), !fileURLs.isEmpty {
            item.kind = .file
            item.fileURLs = fileURLs.map(\.path)
            item.text = fileURLs.map(\.path).joined(separator: "\n")
            item.hash = ClipStore.hash("file:" + item.text!)
        } else if let str = pb.string(forType: .string),
                  !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if let link = Detect.link(str) {
                item.kind = .link
                item.url = link.trimmingCharacters(in: .whitespacesAndNewlines)
            } else if let hex = Detect.color(str) {
                item.kind = .color
                item.colorHex = hex
            }
            item.text = str
            item.isRich = types.contains(.rtf) || types.contains(.html) || types.contains(.rtfd)
            item.hash = ClipStore.hash("text:" + str)
            var total = 0
            for t in first.types {
                if t == concealed || t == transient || t == autoGenerated { continue }
                if let d = first.data(forType: t), d.count < maxRepBytes, total + d.count < maxRepBytes * 2 {
                    blobs[t.rawValue] = d
                    total += d.count
                }
            }
        } else if let img = NSImage(pasteboard: pb), let rep = bestBitmap(pb, img) {
            item.kind = .image
            guard let png = rep.representation(using: .png, properties: [:]) else { return nil }
            item.imageWidth = rep.pixelsWide
            item.imageHeight = rep.pixelsHigh
            item.hash = ClipStore.hash(png)
            blobs[NSPasteboard.PasteboardType.png.rawValue] = png
            for t in first.types where t != .tiff && t != .png {
                if let d = first.data(forType: t), d.count < 2 * 1024 * 1024 { blobs[t.rawValue] = d }
            }
            thumbnail = makeThumbnail(rep, maxSide: 640)
        } else {
            return nil
        }
        return Captured(item: item, blobs: blobs, thumbnail: thumbnail)
    }

    static func bestBitmap(_ pb: NSPasteboard, _ img: NSImage) -> NSBitmapImageRep? {
        if let d = pb.data(forType: .png), let r = NSBitmapImageRep(data: d) { return r }
        if let d = pb.data(forType: .tiff), let r = NSBitmapImageRep(data: d) { return r }
        if let t = img.tiffRepresentation { return NSBitmapImageRep(data: t) }
        return nil
    }

    nonisolated static func makeThumbnail(_ rep: NSBitmapImageRep, maxSide: CGFloat) -> Data? {
        guard let cg = rep.cgImage else { return nil }
        return makeThumbnail(cg, maxSide: maxSide)
    }

    nonisolated static func makeThumbnail(_ cg: CGImage, maxSide: CGFloat) -> Data? {
        let w = CGFloat(cg.width), h = CGFloat(cg.height)
        let scale = min(1, maxSide / max(w, h))
        let tw = max(1, Int(w * scale)), th = max(1, Int(h * scale))
        guard let ctx = CGContext(data: nil, width: tw, height: th, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.interpolationQuality = .high
        ctx.draw(cg, in: CGRect(x: 0, y: 0, width: tw, height: th))
        guard let out = ctx.makeImage() else { return nil }
        return NSBitmapImageRep(cgImage: out).representation(using: .png, properties: [:])
    }
}
